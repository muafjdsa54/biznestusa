async function purgeAndSeed() {
  console.log("=== STEP 1: PURGING PAKISTANI DATA FROM FIRESTORE ===");
  
  for (const colName of ['businesses', 'professionals', 'jobs']) {
    const snap = await getDocs(collection(db, colName));
    console.log(`Found ${snap.size} documents in '${colName}'. Deleting all...`);
    let deletedCount = 0;
    for (const docSnap of snap.docs) {
      await deleteDoc(doc(db, colName, docSnap.id));
      deletedCount++;
    }
    console.log(`Successfully deleted ${deletedCount} documents from '${colName}'.`);
  }

  console.log("\n=== STEP 2: SEEDING GENUINE USA ENTITIES INTO FIRESTORE ===");
  
  console.log(`Seeding ${USA_BUSINESSES.length} USA Businesses...`);
  for (const biz of USA_BUSINESSES) {
    await setDoc(doc(db, 'businesses', biz.id), biz);
    console.log(` + Seeded business: ${biz.name} (${biz.city}, ${biz.state})`);
  }

  console.log(`\nSeeding ${USA_PROFESSIONALS.length} USA Professionals...`);
  for (const pro of USA_PROFESSIONALS) {
    await setDoc(doc(db, 'professionals', pro.id), pro);
    console.log(` + Seeded professional: ${pro.name} (${pro.city}, ${pro.state})`);
  }

  console.log(`\nSeeding ${USA_JOBS.length} USA Jobs...`);
  for (const job of USA_JOBS) {
    await setDoc(doc(db, 'jobs', job.id), job);
    console.log(` + Seeded job: ${job.title} (${job.city}, ${job.state})`);
  }

  console.log("\n=== MIGRATION COMPLETE: All Pakistani entries removed, 100% US verified data seeded! ===");
  process.exit(0);
}

purgeAndSeed().catch(err => {
  console.error("Migration error:", err);
  process.exit(1);
});
